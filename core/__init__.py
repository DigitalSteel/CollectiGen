def __getattr__(name):
    if name in _EXPORTS:
        owner, symbol = _EXPORTS[name]
        # Owner import errors propagate unchanged; failed values are never cached.
        module = _import_module(owner, __name__)
        try:
            value = getattr(module, symbol)
        except AttributeError:
            # Preserve from-import failure semantics for a declared missing name.
            initializing = getattr(getattr(module, "__spec__", None), "_initializing", False)
            qualifier = "partially initialized module" if initializing else "module"
            circular = " (most likely due to a circular import)" if initializing else ""
            location = getattr(module, "__file__", None)
            message = f"cannot import name {symbol!r} from {qualifier} {module.__name__!r}{circular} ({location or 'unknown location'})"
            raise ImportError(message, name=module.__name__, path=location) from None
    elif name in _PUBLIC_MODULES:
        value = _import_module("." + name, __name__)
    else:
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
    globals()[name] = value
    _RESOLVED_EXPORTS.add(name)
    return value


