"""Pure six-dimensional app status and selected-peer observations, never routing.

Inputs are assertions supplied by existing owners after their actual validation.
This module performs no health calls, credential creation, launch or persistence.
"""
from dataclasses import dataclass
from datetime import datetime, timedelta
from enum import Enum

from suite_core.backend_contracts import CapabilityId, ConnectionId, StableId
from suite_core.registry.status_view import Freshness, _freshness
from .app_capabilities import (AppBinding, AppCapabilityDeclaration, CapabilityHold,
    TransportKind, digest_text, exact_id, negotiate, require)

MAX_OBSERVATION_TTL = timedelta(seconds=30)


def aware_time(value):
    require(type(value) is datetime and value.utcoffset() is not None, "aware_observation_time_required")


class InstalledState(str, Enum):
    PRESENT = "present"
    MISSING = "missing"
    CHANGED = "changed_requires_review"
    UNKNOWN = "unknown"


class ConfiguredState(str, Enum):
    SELECTED = "selected"
    MISSING = "not_configured"
    INVALID = "invalid"
    UNKNOWN = "unknown"


class RunningState(str, Enum):
    RUNNING = "running"
    STOPPED = "stopped"
    UNKNOWN = "unknown"


class ReachableState(str, Enum):
    REACHABLE = "reachable"
    UNREACHABLE = "unreachable"
    UNKNOWN = "unknown"


class CompatibleState(str, Enum):
    COMPATIBLE = "compatible"
    INCOMPATIBLE = "incompatible"
    UNKNOWN = "unknown"


class SupportedState(str, Enum):
    SUPPORTED = "supported"
    UNSUPPORTED = "unsupported"
    UNKNOWN = "unknown"


_DIMENSIONS = (InstalledState, ConfiguredState, RunningState, ReachableState, CompatibleState, SupportedState)


@dataclass(frozen=True, slots=True)
class DimensionObservation:
    state: Enum
    source_ref: StableId
    observed_at: datetime
    attempted_at: datetime
    valid_for: timedelta
    evidence_level: str
    reason: str = ""

    def __post_init__(self):
        require(type(self.state) in _DIMENSIONS, "app_dimension_state_required")
        exact_id(self.source_ref)
        aware_time(self.observed_at)
        aware_time(self.attempted_at)
        require(self.attempted_at >= self.observed_at, "observation_attempt_order_required")
        require(type(self.valid_for) is timedelta and timedelta(0) < self.valid_for <= MAX_OBSERVATION_TTL,
                "bounded_observation_ttl_required")
        require(self.evidence_level in {"configured", "provider_reported", "locally_verified"},
                "observation_evidence_required")
        require(type(self.reason) is str and len(self.reason) <= 256
                and not any(ord(c) < 32 for c in self.reason), "bounded_observation_reason_required")

    def freshness(self, now):
        aware_time(now)
        return _freshness(self.observed_at, self.valid_for, now)


@dataclass(frozen=True, slots=True)
class AppEndpointBinding:
    app: AppBinding
    connection_ref: ConnectionId
    instance_id: StableId
    endpoint_ref: StableId
    declaration_digest: str

    def __post_init__(self):
        require(type(self.app) is AppBinding, "app_binding_required")
        self.app.__post_init__()
        exact_id(self.connection_ref, ConnectionId)
        exact_id(self.instance_id)
        exact_id(self.endpoint_ref)
        digest_text(self.declaration_digest)


@dataclass(frozen=True, slots=True)
class SelectedPeerProof:
    """Original validator assertion, not proof generated by these DTOs.

    A pipe name/PID/health response alone cannot supply this assertion. Its future
    producer must verify selected installation, instance and endpoint ownership.
    """
    endpoint: AppEndpointBinding
    source_ref: StableId
    validated_at: datetime
    valid_for: timedelta

    def __post_init__(self):
        require(type(self.endpoint) is AppEndpointBinding, "endpoint_binding_required")
        self.endpoint.__post_init__()
        exact_id(self.source_ref)
        aware_time(self.validated_at)
        require(type(self.valid_for) is timedelta and timedelta(0) < self.valid_for <= MAX_OBSERVATION_TTL,
                "bounded_peer_proof_ttl_required")

    def valid_at(self, endpoint, now):
        aware_time(now)
        return self.endpoint == endpoint and _freshness(self.validated_at, self.valid_for, now) is Freshness.FRESH


@dataclass(frozen=True, slots=True)
class AppAvailability:
    binding: AppBinding
    installed: DimensionObservation
    configured: DimensionObservation
    running: DimensionObservation
    reachable: DimensionObservation
    compatible: DimensionObservation
    capability_supported: DimensionObservation
    capability_id: CapabilityId
    endpoint: AppEndpointBinding | None = None
    peer_proof: SelectedPeerProof | None = None

    def __post_init__(self):
        require(type(self.binding) is AppBinding, "app_binding_required")
        self.binding.__post_init__()
        exact_id(self.capability_id, CapabilityId)
        for name, kind in zip(("installed", "configured", "running", "reachable", "compatible", "capability_supported"), _DIMENSIONS):
            value = getattr(self, name)
            require(type(value) is DimensionObservation and type(value.state) is kind, "exact_app_dimension_required")
            value.__post_init__()
        require(self.endpoint is None or type(self.endpoint) is AppEndpointBinding
                and self.endpoint.app == self.binding, "availability_endpoint_binding_mismatch")
        require(self.peer_proof is None or type(self.peer_proof) is SelectedPeerProof
                and self.peer_proof.endpoint == self.endpoint, "availability_peer_binding_mismatch")


@dataclass(frozen=True, slots=True)
class AvailabilityDecision:
    enabled: bool
    visible: bool
    reason: str
    negotiation: object = None

    @property
    def execution_authorized(self):
        return False


def project_availability(declaration, observation, capability_id, *, now, request_versions=(1,),
                         response_versions=(1,), transport=TransportKind.LOCAL, relevant=True):
    """Current availability only; recipient scope/effects still require admission."""
    aware_time(now)
    require(type(relevant) is bool, "explicit_relevance_required")
    require(type(declaration) is AppCapabilityDeclaration and type(observation) is AppAvailability,
            "exact_app_projection_inputs_required")
    declaration.__post_init__()
    observation.__post_init__()
    require(observation.binding == declaration.binding and observation.capability_id == capability_id,
            "availability_declaration_binding_mismatch")
    try:
        selected = negotiate(declaration, capability_id, request_versions=request_versions,
                             response_versions=response_versions, transport=transport)
    except CapabilityHold as error:
        return AvailabilityDecision(False, relevant, str(error))
    positive = (InstalledState.PRESENT, ConfiguredState.SELECTED, RunningState.RUNNING,
                ReachableState.REACHABLE, CompatibleState.COMPATIBLE, SupportedState.SUPPORTED)
    for name, expected in zip(("installed", "configured", "running", "reachable", "compatible", "capability_supported"), positive):
        value = getattr(observation, name)
        fresh = value.freshness(now)
        # Retained last-good evidence cannot qualify a later failed attempt.
        if value.attempted_at > now or value.attempted_at != value.observed_at:
            return AvailabilityDecision(False, True, name + "_latest_attempt_unverified")
        if fresh is not Freshness.FRESH:
            return AvailabilityDecision(False, True, name + "_" + fresh.value)
        if value.state is not expected:
            return AvailabilityDecision(False, relevant if value.state is SupportedState.UNSUPPORTED else True,
                                        name + "_" + value.state.value)
        if name != "configured" and value.evidence_level == "configured":
            return AvailabilityDecision(False, True, name + "_not_runtime_verified")
    endpoint, proof = observation.endpoint, observation.peer_proof
    if endpoint is None or endpoint.declaration_digest != declaration.digest:
        return AvailabilityDecision(False, True, "endpoint_declaration_unverified")
    if proof is None or not proof.valid_at(endpoint, now):
        return AvailabilityDecision(False, True, "selected_peer_unverified")
    return AvailabilityDecision(True, True, "available", selected)
