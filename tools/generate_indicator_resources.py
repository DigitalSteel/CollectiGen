"""Regenerate embedded indicator glyphs with the installed PySide6 rcc tool."""
from pathlib import Path
import subprocess,sys


def main():
    root=Path(__file__).resolve().parents[1]
    tool=Path(sys.executable).with_name('pyside6-rcc.exe' if sys.platform=='win32' else 'pyside6-rcc')
    work=root/'.tmp'/'indicator-resource-inputs';work.mkdir(parents=True,exist_ok=True)
    if work.is_relative_to(root/'.tmp'):
        entries=[]
        for tone,color in [('dark','#20242a'),('light','#ffffff')]:
            for name,shape in [('check','<path d="M3 8l3 3 7-7" fill="none" stroke="COLOR" stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round"/>'),('partial','<path d="M4 8h8" stroke="COLOR" stroke-width="2.4" stroke-linecap="round"/>'),('radio','<circle cx="8" cy="8" r="3.2" fill="COLOR"/>')]:
                filename=name+'-'+tone+'.svg';(work/filename).write_bytes(('<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16">'+shape.replace('COLOR',color)+'</svg>').encode());entries.append('<file>'+filename+'</file>')
        (work/'indicators.qrc').write_bytes(('<RCC><qresource prefix="/collectigen/indicators">'+''.join(entries)+'</qresource></RCC>').encode())
        result=subprocess.run([str(tool),'indicators.qrc'],cwd=work,capture_output=True,check=True)
        output=root/'qt_app/indicator_resources.py'
        output.write_bytes(b'# Generated by tools/generate_indicator_resources.py; do not hand edit.\n'+result.stdout.replace(b'\r\n',b'\n'))


if __name__=='__main__':main()
